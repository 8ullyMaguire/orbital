#!/usr/bin/env python3
"""Fold the enriched link-in-bio links back into the members already imported.

    ./merge.py --stage stage-creators.csv --enrich enrich.json --out merge.csv
    psql "$DATABASE_URL" -f merge.sql      # generated next to --out; idempotent

Why not just re-run build.py + import.sql: `build.py` skips a performer whose
identity is already on Orbital, so a second build emits nothing for the 44,817
members the first one created, and their newly discovered socials never reach the
staging table. This step keys on the handle instead and inserts only what is missing,
using the same guards as `import.sql` — a re-run (and a crawl that finds nothing)
inserts 0 rows.

Links are appended (position = max + 1 …) because the existing order is the one the
record came with, and a discovered social is an addition, not a reordering.
"""
import argparse
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from build import classify  # noqa: E402

SQL = """-- generated by scripts/creator-sources/merge.py
\\set ON_ERROR_STOP on
BEGIN;

CREATE TEMP TABLE stg (
  handle text,
  links  jsonb,
  tags   jsonb
) ON COMMIT DROP;

\\copy stg FROM '__STAGE__' WITH (FORMAT csv)

WITH new_links AS (
  SELECT u.id AS user_id,
         l->>'url' AS url, l->>'label' AS label, l->>'icon' AS icon,
         (SELECT coalesce(max(position), -1) FROM links WHERE user_id = u.id)
           + x.ord AS position
    FROM stg s
    JOIN users u ON u.handle = s.handle
    CROSS JOIN LATERAL jsonb_array_elements(s.links) WITH ORDINALITY AS x(l, ord)
   WHERE NOT EXISTS (SELECT 1 FROM links li
                      WHERE li.user_id = u.id AND li.url = l->>'url')
)
INSERT INTO links (user_id, url, label, icon, position)
SELECT user_id, url, coalesce(nullif(label, ''), url), coalesce(nullif(icon, ''), 'link'),
       position
  FROM new_links;

INSERT INTO tags (user_id, tag_slug)
SELECT DISTINCT u.id, t.tag
  FROM stg s
  JOIN users u ON u.handle = s.handle
  CROSS JOIN LATERAL jsonb_array_elements_text(s.tags) AS t(tag)
 WHERE t.tag ~ '^[a-z0-9][a-z0-9+.#-]{0,29}$'
ON CONFLICT DO NOTHING;

SELECT (SELECT count(*) FROM stg) AS handles_touched,
       (SELECT count(*) FROM users) AS users_total,
       (SELECT count(*) FROM links) AS links_total,
       (SELECT count(*) FROM tags)  AS tags_total;

COMMIT;
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--stage', default=os.path.join(HERE, 'stage-creators.csv'))
    ap.add_argument('--enrich', default=os.path.join(HERE, 'enrich.json'))
    ap.add_argument('--out', default=os.path.join(HERE, 'merge.csv'))
    args = ap.parse_args()

    enrich = {k: v for k, v in json.load(open(args.enrich)).items() if v}
    rows, added = 0, 0
    with open(args.stage, newline='') as f, open(args.out, 'w', newline='') as out:
        w = csv.writer(out, lineterminator='\n')
        for row in csv.reader(f):
            if not row or len(row) < 8:
                continue
            handle = row[0]
            staged = json.loads(row[7] or '[]')
            tags = set(json.loads(row[6] or '[]'))
            have = {l.get('url') for l in staged}
            keys = set()
            for l in staged:
                c = classify(l.get('url') or '')
                if c and c[3]:
                    keys.add(c[3])
            new, seen = [], set()
            for l in staged:
                u = (l.get('url') or '').strip()
                if u in enrich:
                    for e in enrich[u]:
                        c = classify(e['url'])
                        if not c or c[3] in keys or c[3] in seen or e['url'] in have:
                            continue
                        seen.add(c[3])
                        new.append({'url': e['url'], 'label': e['label'], 'icon': e['icon']})
                        tags.add(c[0])
            if not new:
                continue
            rows += 1
            added += len(new)
            w.writerow([handle, json.dumps(new), json.dumps(sorted(tags))])
    print(f'handles with new links: {rows}, links to insert: {added} -> {args.out}')

    sql = SQL.replace('__STAGE__', os.path.abspath(args.out))
    sqli = os.path.join(os.path.dirname(os.path.abspath(args.out)), 'merge.sql')
    open(sqli, 'w').write(sql)
    print('sql ->', sqli)


if __name__ == '__main__':
    main()
